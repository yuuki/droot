#!/usr/bin/env bash
#
# Prints the Homebrew formula of a release (droot.rb of the tap
# yuuki/homebrew-droot), with the URLs and SHA-256 of its archives taken
# from the checksums.txt of the release:
#
#   script/homebrew-formula.sh VERSION CHECKSUMS
#
# VERSION is a release (0.8.0 or v0.8.0; pre-releases are not published in
# the tap). CHECKSUMS is the checksums.txt of that release; verify it first
# (see documentation/development.md#releasing). The formula installs the
# archive of macOS or Linux, on amd64 or arm64; Homebrew does not support
# 32-bit ARM.
set -euo pipefail

die() { echo "homebrew-formula: $*" >&2; exit 1; }
[[ $# -eq 2 ]] || { echo "usage: $0 VERSION CHECKSUMS" >&2; exit 2; }

version=${1#v}
checksums=$2
repo=https://github.com/yuuki/droot
[[ $version =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$ ]] ||
  die "not a release version (MAJOR.MINOR.PATCH): $1"
[[ -f $checksums ]] || die "$checksums: no such file"

# sha256 ASSET: the checksum of ASSET in CHECKSUMS ("<sha256>  <name>").
sha256() {
  local sum
  sum=$(awk -v name="$1" '$2 == name || $2 == "*" name { print $1; exit }' "$checksums")
  [[ -n $sum ]] || die "$checksums has no checksum for $1"
  [[ $sum =~ ^[0-9a-f]{64}$ ]] || die "$checksums: not a SHA-256 for $1: $sum"
  printf '%s' "$sum"
}

# resource ASSET: the url and sha256 lines of ASSET.
resource() {
  local sum
  sum=$(sha256 "$1") || exit
  printf '      url "%s/releases/download/v%s/%s"\n' "$repo" "$version" "$1"
  printf '      sha256 "%s"\n' "$sum"
}

darwin_arm64=$(resource droot_darwin_arm64.zip)
darwin_amd64=$(resource droot_darwin_amd64.zip)
linux_arm64=$(resource droot_linux_arm64.tar.gz)
linux_amd64=$(resource droot_linux_amd64.tar.gz)

cat <<EOF
# Generated by script/homebrew-formula.sh of yuuki/droot from the
# checksums.txt of v$version. Do not edit by hand.
class Droot < Formula
  desc "Super-simple chroot-based application container engine"
  homepage "$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
$darwin_arm64
    end
    on_intel do
$darwin_amd64
    end
  end

  on_linux do
    on_arm do
$linux_arm64
    end
    on_intel do
$linux_amd64
    end
  end

  head do
    url "$repo.git", branch: "master"
    depends_on "go" => :build
  end

  def install
    if build.head?
      ENV["CGO_ENABLED"] = "0"
      system "go", "build", *std_go_args(ldflags: "-s -w"), "./cmd/droot"
      man1.install "documentation/droot.1"
    else
      # The archive contains droot_<os>_<arch>/, where Homebrew starts.
      bin.install "droot"
      man1.install "droot.1"
    end
  end

  test do
    assert_match "droot version", shell_output("#{bin}/droot --version")
  end
end
EOF
